/* Writes the report-only checks' findings for one volume as markdown
 * (docs/governance.md "Report-only checks"; src/tools/report-checks.ts):
 *
 *   npm run report-checks                          volume co, to stdout
 *   npm run report-checks -- --out docs/reviews/report-only-checks.md
 *
 * Read-only on the ledger. `npm run check` runs the same checks and prints
 * the same findings, one line each. */
import fs from "node:fs";
import path from "node:path";
import { createEngine } from "../src/engine/engine";
import { loadLedgerFromDisk } from "../src/tools/check";
import {
  REPORT_CHECKS, benefitStatusFindings, declaredDefault, ignoredDeclaredDefaults, isSharedItem,
  regulationProgram, sharedItemsOfOneProgram,
} from "../src/tools/report-checks";
import { gitShaWithDirtySuffix } from "./git-sha";

const root = path.resolve(import.meta.dirname, "..");
const args = process.argv.slice(2);
const volume = args.includes("--volume") ? args[args.indexOf("--volume") + 1] : "co";
const out = args.includes("--out") ? args[args.indexOf("--out") + 1] : null;

const ledger = loadLedgerFromDisk(root, volume);
const engine = createEngine(ledger.items, ledger.meta, {
  sourceIds: ledger.sourceIds, questionIds: ledger.questionIds,
  unverifiedSourceIds: ledger.unverifiedSourceIds ?? [], sourceTexts: ledger.sourceTexts ?? {},
});
const input = {
  engine, items: ledger.items, meta: ledger.meta, chapterOf: ledger.chapterOf,
  sourceCitations: ledger.sourceCitations ?? {}, cases: ledger.cases,
};

const cell = (s: string) => s.replace(/\s+/g, " ").replace(/\|/g, "\\|");
const L: string[] = [];
const sha = gitShaWithDirtySuffix(root).slice(0, 7);
L.push("# Report-only checks");
L.push("");
L.push(`The three report-only checks of \`npm run check\` (docs/governance.md, "Report-only checks"; src/tools/report-checks.ts), run on volume \`${volume}\` at ${sha}. Generated by \`npm run report-checks -- --out docs/reviews/report-only-checks.md\`. Nothing here was fixed: each list is candidates for the owners named in docs/handoff-2026-11-24.md.`);
L.push("");

// 1
const declared = ledger.items.map(declaredDefault).filter((d) => d !== null);
const ignored = ignoredDeclaredDefaults(engine);
const facts = new Set(ignored.map((f) => f.fact.id));
L.push("## Counts");
L.push("");
L.push("| Check | Findings | Blocking |");
L.push("|---|---|---|");
const shared = sharedItemsOfOneProgram(input);
const benefits = benefitStatusFindings(ledger.cases);
const counts: Record<string, number> = {
  "ignored-default": ignored.length, "shared-one-program": shared.length, "benefit-status-receipt": benefits.length,
};
for (const c of REPORT_CHECKS) L.push(`| ${c.id}: ${c.title} | ${counts[c.id]} | ${c.blocking ? "yes" : "no"} |`);
L.push("");

L.push("## 1. Ignored declared defaults (FB-06)");
L.push("");
L.push(`A supplied fact whose meaning or precision says what an unstated value is read as (${declared.length} facts do, by the sentence patterns "If not stated, <program> reads this as …" and "read as … when not stated"), and a reader the statement covers that reads the fact bare: not as the first argument of an \`otherwise\`, and with no \`unknown\` test of it. Left unstated, the fact makes that reader cannot-determine, not the declared reading. The statement covers the readers it names (by id or identifier) when it names any, else the readers of the programs named before its verb, else every reader. **${ignored.length} reader(s) of ${facts.size} fact(s).** Candidates: a reader can be right to require the fact (the statement may be stale), and a default stated only in prose can be missed.`);
L.push("");
L.push("| Fact | Declared | Reader (program) |");
L.push("|---|---|---|");
for (const f of ignored) {
  L.push(`| ${f.fact.id} \`${f.fact.identifier}\` | ${cell(f.statement)} | ${f.reader.id} \`${f.reader.identifier}\` (${f.reader.program}) |`);
}
L.push("");

// 2
const inScope = ledger.items.filter((it) => isSharedItem(it, ledger.chapterOf));
const multi = inScope.filter((it) => {
  const ps = new Set([...(it.sources ?? []), ...(it.versions ?? []).map((v) => v.source ?? "")].map((s) => regulationProgram(ledger.sourceCitations?.[s])).filter((p) => p));
  return ps.size > 1;
}).length;
const cites = shared.filter((f) => f.citesOnly);
const reads = shared.filter((f) => f.reads.length);
const byProgram = new Map<string, number>();
for (const f of cites) byProgram.set(f.citesOnly!.program, (byProgram.get(f.citesOnly!.program) ?? 0) + 1);
const byKind = new Map<string, number>();
for (const f of shared) byKind.set(f.item.kind, (byKind.get(f.item.kind) ?? 0) + 1);
L.push("## 2. Shared items citing or reading one program");
L.push("");
L.push(`A preview of the four-test sharing rule (docs/reviews/cross-program-primitives.md). ${inScope.length} items are shared (program All, or in the shared chapter). An excerpt belongs to a program's regulation by its citation line: SNAP 7 CFR 271–274 and 10 CCR 2506-1; Medicaid 42 CFR 430–439 and 10 CCR 2505-10; CHP+ 42 CFR 457 and 10 CCR 2505-3; Colorado Works 9 CCR 2503-6 and 45 CFR 260–265; Adult Financial 9 CCR 2503-5; CCCAP 8 CCR 1403-1 and 45 CFR 98; LEAP 9 CCR 2503-7; SUN Bucks 7 CFR 292. Statutes, 20 CFR 416 (the SSI method several programs adopt) and guidance belong to none. An item is listed when every program regulation it cites is one program's, or when its derivation reads a program-prefixed item. **${shared.length} items: ${cites.length} cite only one program's regulation, ${reads.length} read a program-prefixed item** (${[...byKind].map(([k, n]) => `${n} ${k}`).join(", ")}). ${multi} more shared items cite the regulations of two or more programs and are not listed.`);
L.push("");
L.push("| Program cited alone | Items |");
L.push("|---|---|");
for (const [p, n] of [...byProgram].sort((a, b) => b[1] - a[1])) L.push(`| ${p} | ${n} |`);
L.push("");
L.push("| Item | Kind | Finding |");
L.push("|---|---|---|");
for (const f of shared) {
  const parts: string[] = [];
  if (f.citesOnly) parts.push(`cites only ${f.citesOnly.program} (${f.citesOnly.sources.join(", ")})`);
  if (f.reads.length) parts.push(`reads ${f.reads.map((r) => `\`${r.identifier}\` (${r.id}${r.declared ? ", declared in accepts_from" : ""})`).join(", ")}`);
  L.push(`| ${f.item.id} \`${f.item.identifier}\` | ${f.item.kind} | ${parts.join("; ")} |`);
}
L.push("");

// 3
const households = new Map<string, typeof benefits>();
for (const f of benefits) households.set(f.caseId, [...(households.get(f.caseId) ?? []), f]);
const tally = new Map<string, number>();
for (const f of benefits) {
  const k = `${f.benefit}: ${f.kind === "status-without-receipt" ? "status, no receipt" : "receipt, status false"}`;
  tally.set(k, (tally.get(k) ?? 0) + 1);
}
L.push("## 3. Benefit status without a receipt");
L.push("");
L.push(`Decision pending (docs/handoff-2026-11-24.md, section 3, item 4). The status facts \`receives_ssi\`, \`receives_tanf_cash\` and \`adult_financial_program_received\` are person facts as of the determination date, so the month compared is the determination month. A receipt is in the month by its \`month\` or \`date\`; one with neither recurs from its \`start_date\` through its \`end_date\` (a one-time payment with neither is in no month). The only stated reason the ledger has today is \`retains_ssi_status_without_payment\` for SSI. Another member's receipt of the kind (a payee's, say) is noted, not taken as a reason. **${benefits.length} findings in ${households.size} households.**`);
L.push("");
L.push("| Benefit and direction | Persons |");
L.push("|---|---|");
for (const [k, n] of [...tally].sort()) L.push(`| ${k} | ${n} |`);
L.push("");
for (const [caseId, fs_] of households) {
  L.push(`- **${caseId}**`);
  for (const f of fs_) {
    const others = f.othersWithReceipt.length ? `; ${f.othersWithReceipt.join(", ")} states one` : "";
    L.push(f.kind === "status-without-receipt"
      ? `  - ${f.person}: \`${f.status}\` ${JSON.stringify(f.statusValue)}, no \`${f.receiptKind}\` receipt in ${f.month}, no stated reason${others}`
      : `  - ${f.person}: a \`${f.receiptKind}\` receipt in ${f.month}, \`${f.status}\` ${JSON.stringify(f.statusValue)}`);
  }
}
L.push("");

const text = L.join("\n");
if (out) fs.writeFileSync(path.resolve(root, out), text);
else process.stdout.write(text);
