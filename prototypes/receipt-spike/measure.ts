// Receipt spike: size and readability of each slice in each model. Writes the
// pattern English an approver reads (the same renderer as the app's item
// page) for every item of each slice, and counts items, tree nodes, words,
// supplied facts read, and reader-supplied defaults (`otherwise` on a
// supplied fact).
import fs from "node:fs";
import path from "node:path";
import { loadModel, spikeDir, type Model } from "./ledger";
import { block } from "../../src/engine/render";
import type { Expr } from "../../src/engine/types";

const SLICES: Record<string, Record<"old" | "a" | "b", string[]>> = {
  "LEAP unearned income": {
    old: ["leap_person_unearned_income", "unearned_income_prior_thirty_days", "leap_excluded_unearned_income", "leap_excluded_source_receipts", "leap_excluded_receipts_in_lump_sum", "leap_person_one_time_income"],
    a: ["leap_person_unearned_income", "leap_counted_recurring_receipts", "leap_social_security_whole_dollars", "leap_ssi_whole_dollars", "leap_receipts_set_aside", "leap_one_time_receipts_in_period", "leap_receipt_treatment_table", "leap_income_verification_period_start"],
    b: ["leap_person_unearned_income"],
  },
  "SNAP unearned income": {
    old: ["snap_person_unearned_income", "snap_excluded_unearned_income"],
    a: ["snap_person_unearned_income", "snap_receipt_treatment_table", "snap_counted_recurring_receipts", "snap_irregular_unearned_receipts_in_quarter", "snap_excluded_irregular_receipts", "snap_excluded_charitable_receipts"],
    b: ["snap_person_unearned_income"],
  },
  "Adult Financial deeming": {
    old: ["af_relative_deemable_unearned_income", "af_unearned_income_other_than_ssi", "af_excluded_unearned_income"],
    a: ["af_relative_deemable_unearned_income", "af_unearned_income_other_than_ssi", "af_counted_unearned_receipts", "af_receipt_treatment_table"],
    b: ["af_relative_deemable_unearned_income", "af_unearned_income_other_than_ssi", "af_counted_income".replace("af_counted_income", "af_counted_unearned_income")],
  },
};
const models = { old: loadModel("old"), a: loadModel("a"), b: loadModel("b") };
const nodes = (e: Expr): number => (Array.isArray(e) ? 1 + (e as Expr[]).reduce((t, x) => t + nodes(x), 0) : 1);
function stats(m: Model, ids: string[]) {
  let n = 0, words = 0, defaults = 0;
  const supplied = new Set<string>();
  const text: string[] = [];
  for (const id of ids) {
    const it = m.ix.byIdentifier.get(id)!;
    let body: string[];
    if (it.kind === "parameter") {
      const v = (it.versions?.[it.versions.length - 1]?.value ?? it.value) as Record<string, unknown>;
      body = Object.entries(v).map(([k, x]) => `  ${k}: ${x}`);
    } else {
      n += nodes(it.derived!);
      body = block(m.ix, it.derived!);
      const walk = (e: Expr) => {
        if (typeof e === "string") { const f = m.ix.byIdentifier.get(e); if (f?.kind === "supplied") supplied.add(e); }
        if (!Array.isArray(e)) return;
        if (e[0] === "otherwise" && typeof e[1] === "string" && m.ix.byIdentifier.get(e[1])?.kind === "supplied") defaults++;
        for (const x of e as Expr[]) walk(x);
      };
      walk(it.derived!);
    }
    const t = `${it.id} ${it.name} (${it.identifier})\n` + body.join("\n");
    words += t.split(/\s+/).length;
    text.push(t);
  }
  return { items: ids.length, nodes: n, words, supplied: supplied.size, defaults, text };
}
const rows: string[] = ["| Slice | Model | Items | Tree nodes | Words of pattern English | Supplied facts read | `otherwise` on a supplied fact |", "|---|---|---|---|---|---|---|"];
const doc: string[] = [];
for (const [slice, per] of Object.entries(SLICES)) {
  for (const k of ["old", "a", "b"] as const) {
    const s = stats(models[k], per[k]);
    rows.push(`| ${slice} | ${k === "old" ? "today" : k.toUpperCase()} | ${s.items} | ${s.nodes} | ${s.words} | ${s.supplied} | ${s.defaults} |`);
    doc.push(`\n## ${slice}: ${k === "old" ? "today" : "Model " + k.toUpperCase()}\n\n\`\`\`\n${s.text.join("\n\n")}\n\`\`\``);
  }
}
const out = path.join(spikeDir, "results", "readability.md");
fs.writeFileSync(out, "# Receipt spike: the slices as an approver reads them\n\nGenerated by measure.ts with the app's pattern-English renderer.\n\n" + rows.join("\n") + "\n" + doc.join("\n") + "\n");
